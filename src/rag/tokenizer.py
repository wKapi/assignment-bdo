"""ქართული ტექსტის ტოკენიზაცია BM25-ისთვის.

ქართულს მთავრულ/ასომთავრული რეგისტრი არ აქვს, ამიტომ `lower()`
პრაქტიკულად არაფერს ცვლის (ლათინური ჩანართებისთვის მაინც ვტოვებთ).
ორი რეალური პრობლემაა.

 „შვებულება“, „შვებულების“, „შვებულებას“,
„შვებულებაზე“ BM25-ისთვის ოთხი სხვადასხვა ტოკენია. ამიტომ ბრუნვისა და
რიცხვის გავრცელებულ სუფიქსებს ვაჭრით, და ვაჭრით **განმეორებით**:
„სამუშაოს“ → „სამუშაო“ → „სამუშა“, რომ „სამუშაო“-ს იგივე ფუძე
შეხვდეს. ეს სრული მორფოლოგიური ანალიზი არ არის და არც უნდა იყოს —
გარე დამოკიდებულების გარეშე მოძიების ხარისხს შესამჩნევად აუმჯობესებს.

**ლექსიკის სხვაობა.** თანამშრომელი „სახლიდან მუშაობას“ ეძებს,
პოლიტიკაში კი „დისტანციური მუშაობა“ წერია; „ბიულეტენი“ პოლიტიკაში
„ავადმყოფობის შვებულებაა“. BM25-ს სინონიმები არ ესმის, ამიტომ
**კითხვას** (და არა ინდექსს) მცირე ლექსიკონით ვაფართოებთ.
"""

from __future__ import annotations

import re

TOKEN_PATTERN = re.compile(r"[\wႠ-ჿ]+", re.UNICODE)

# გრძელიდან მოკლისკენ — თითო გავლაზე პირველი დამთხვევა იჭრება
SUFFIXES: tuple[str, ...] = (
    "ებისთვის", "ებისგან", "ისთვის", "ებიდან", "ებისას",
    "ისგან", "ებთან", "ებზე", "ებში", "ებით", "ებად", "ების", "ებმა",
    "ისას", "იდან", "ებს", "ები",
    "თან", "დან", "ზე", "ში", "ით", "ად", "ის", "მა",
    "ებ", "ს", "ი", "ო", "ე", "ა",
)

MIN_STEM_LENGTH = 3
MAX_STRIP_ROUNDS = 4

# ფუძე კითხვაში → ფუძეები, რომლებიც დოკუმენტებში გვხვდება
QUERY_SYNONYMS: dict[str, tuple[str, ...]] = {
    "სახლ": ("დისტანციურ",),
    "ბიულეტენ": ("ავადმყოფობ",),
    "ავად": ("ავადმყოფობ",),
    "დასვენებ": ("შვებულებ",),
    "დეკრეტ": ("მშობლ",),
    "გამოცდ": ("სასწავლო",),
    "ქვითრ": ("ხარჯ",),
    "ქვითარ": ("ხარჯ",),
}


def stem(token: str) -> str:
    """სუფიქსებს განმეორებით აჭრის, სანამ ფუძე საკმარისად გრძელია."""
    for _ in range(MAX_STRIP_ROUNDS):
        for suffix in SUFFIXES:
            if token.endswith(suffix) and len(token) - len(suffix) >= MIN_STEM_LENGTH:
                token = token[: -len(suffix)]
                break
        else:
            break
    return token


def tokenize(text: str) -> list[str]:
    """ტექსტი → ფუძეების სია BM25-ისთვის."""
    return [stem(match.group().lower()) for match in TOKEN_PATTERN.finditer(text)]


def tokenize_query(text: str) -> list[str]:
    """იგივე, პლუს სინონიმები — მხოლოდ კითხვისთვის."""
    tokens = tokenize(text)
    expanded = list(tokens)
    for token in tokens:
        expanded.extend(QUERY_SYNONYMS.get(token, ()))
    return expanded
